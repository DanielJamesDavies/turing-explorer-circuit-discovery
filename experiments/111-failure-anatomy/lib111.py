def outcome(s):
    """062 paper_main.py `outcome`, one class per non-vacuous circuit, in order: pass; undef (a Z / A / C or necessity
    score missing); nec (fails necessity); zero (necessity holds, Z out of band); mean (fails only A and/or C)."""
    ok = {k: s[c].between(*L.BAND) for k, c in zip("ZAC", L.HEAD)}
    undef = s[L.HEAD + [L.NEC]].isna().any(axis=1)
    nec = s[L.NEC] >= L.NEC_MIN
    return pd.Series(np.select([s["pass"], undef, ~nec, ~ok["Z"]], ["pass", "undef", "nec", "zero"], "mean"),
                     index=s.index)


