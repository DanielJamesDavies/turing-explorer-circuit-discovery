def test_flags(s):
    """Non-exclusive per-test flags of a circuit: which part of the rule it breaks (a missing score counts as
    'undefined' for that test, not as low or high)."""
    f = {}
    for k, c in zip("ZAC", L.HEAD):
        x = pd.to_numeric(s[c], errors="coerce")
        f[k + "_low"] = x < L.BAND[0]
        f[k + "_high"] = x > L.BAND[1]
        f[k + "_undef"] = x.isna()
    n = pd.to_numeric(s[L.NEC], errors="coerce")
    f["nec_low"] = n < L.NEC_MIN
    f["nec_undef"] = n.isna()
    return pd.DataFrame(f, index=s.index)


def combo(flags):
    """A readable combination label per failing circuit, e.g. 'A<0.75 + C<0.75'."""
    lab = {"Z_low": "Z<0.75", "Z_high": "Z>1.5", "Z_undef": "Z undef", "A_low": "A<0.75", "A_high": "A>1.5",
           "A_undef": "A undef", "C_low": "C<0.75", "C_high": "C>1.5", "C_undef": "C undef", "nec_low": "nec<0.9",
           "nec_undef": "nec undef"}
    cols = list(lab)
    return flags[cols].apply(lambda r: " + ".join(lab[c] for c in cols if r[c]) or "none", axis=1)


def vac_terms(df):
    """Which denominator makes a row vacuous (merge.vacuous v2: a_pos_tk <= 0, or a_pos_tk - e < 0.05 a_pos_tk for
    e in e0_tk (Z and necessity), eM_topk_tk (A), eN_topk_tk (C)). Non-exclusive columns."""
    ap = pd.to_numeric(df["a_pos_tk"], errors="coerce")
    out = {"apos_le0": ap <= 0}
    for name, c in (("Z_nec", "e0_tk"), ("A", "eM_topk_tk"), ("C", "eN_topk_tk")):
        e = pd.to_numeric(df[c], errors="coerce")
        out[name] = (ap - e) < 0.05 * ap
    return pd.DataFrame(out, index=df.index)


def spec_frame(model):
    """Production specificity rows (main/spec.shard*.jsonl), one row per (seed, pi), last kept."""
    rows = L.read_rows(L.find(model, "out", "main"), "spec")
    d = L.frame(rows, keys=("seed", "pi"))
    for c in ("target_faith_pre", "sibling_faith_median", "control_faith_median", "switched_on_circuit",
              "switched_on_empty", "in_topk_circuit", "in_topk_clean", "rank_clean", "K"):
        if c in d:
            d[c] = pd.to_numeric(d[c], errors="coerce")
    return d


def per_target_spec(sp):
    """wcm_specificity.target_specificity per seed (amp_any, rank_clean, near_threshold), plus amp flag per pi."""
    out = []
    for seed, g in sp.groupby("seed"):
        recs = g.to_dict("records")
        t = target_specificity(recs)
        for r in recs:
            t["amp_" + r["pi"]] = amplifier_flag(r)
        t["seed"] = seed
        out.append(t)
    return pd.DataFrame(out).set_index("seed")


