"""120 report (CPU).

1. 117's report117.main(), unchanged, pointed at 120's rows (out/wcm/dan215) -> out/report.md, out/report.json. Its
   faithfulness table is the errors-zeroed scoring; its structure checks, nulls, verdicts and "full model" column are
   the error-zeroed frames (the "full model" there is the ERROR-FREE full model).
2. Paired comparisons with 117 (errors live; 117's out/report.json and out/wcm/dan215/eval.jsonl, read-only) and the
   diagnostic (out/diag/eval.jsonl) -> out/report120.md, out/report120.json.

  PYTHONPATH=src python -X utf8 experiments/120-known-circuits-errors-zeroed/report120.py
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import common120 as C  # noqa: E402
import lib117 as L  # noqa: E402
import merge as MG  # noqa: E402
import report117 as RP  # noqa: E402

D120 = C.WCM / "dan215"
D117 = C.E117 / "out" / "wcm" / "dan215"
COLS = MG.HEAD + ["phi_sup_blind_tk"]


def run_report117():
    old_out, old_d = L.OUT, RP.D
    L.OUT, RP.D = C.OUT, D120               # targets.json is a copy of 117's (out/targets.json)
    try:
        RP.main()
    finally:
        L.OUT, RP.D = old_out, old_d
    return json.loads((C.OUT / "report.json").read_text())


def scored(df):
    df = df.copy()
    for c in COLS + MG.VAC_BASE + ["a_pos_tk"]:
        if c in df:
            df[c] = pd.to_numeric(df[c], errors="coerce")
    df["vac"] = MG.vacuous(df).values
    df["pass"] = False
    ok = ~df.vac
    df.loc[ok, "pass"] = MG.passes(df[ok]).values
    return df


def eval_frames():
    e120 = pd.DataFrame([r for r in RP.rows(D120 / "eval.jsonl") if "error" not in r])
    e117 = pd.DataFrame([r for r in RP.rows(D117 / "eval.jsonl") if "error" not in r])
    k = ["seed", "circuit", "data", "held", "fold"]
    e120 = e120.drop_duplicates(k, keep="last").reset_index(drop=True)
    e117 = e117.drop_duplicates(k, keep="last").reset_index(drop=True)
    live = pd.DataFrame([dict(r["live"], **{c: r[c] for c in k}) for r in e120.to_dict("records")])
    dg = pd.DataFrame(RP.rows(C.OUT / "diag" / "eval.jsonl"))
    if not dg.empty:
        dg = dg.drop_duplicates(k + ["err_mode"], keep="last").reset_index(drop=True)
        dg = scored(dg)
    return scored(e120), scored(live), scored(e117), dg


def cellfmt(sub):
    if sub is None or sub.empty:
        return "-"
    m = sub[COLS].mean()
    return "%.2f/%.2f/%.2f/%.2f %s" % (tuple(m.values) + ("P" if bool(sub["pass"].any()) else "-",))


def task_cell(sub):
    if sub is None or sub.empty:
        return "-"
    return "%.2f (%d/%d)" % (float(sub.free0_tk.mean()), int(sub["pass"].sum()), len(sub))


def pick(df, seed, cname, data, held="strong"):
    if df is None or df.empty:
        return None
    return df[(df.seed == seed) & (df.circuit == cname) & (df.data == data) & (df.held == held)]


def published(task):
    out = {}
    for cn, c in L.CLASSES.items():
        if c["task"] != task:
            continue
        for lh in c["heads"]:
            out.setdefault(lh, []).append((cn, c["role"]))
    return out


def main():
    rep120 = run_report117()
    rep117 = json.loads((C.E117 / "out" / "report.json").read_text())
    sel = json.loads((C.OUT / "targets.json").read_text())
    keys = [c["key"] for p in sel["pathways"].values() for c in p["chosen"]]
    pw_of = {c["key"]: p for p, d in sel["pathways"].items() for c in d["chosen"]}
    st120 = pd.DataFrame(RP.rows(D120 / "status.jsonl")).drop_duplicates("seed", keep="last").set_index("seed")
    st117 = pd.DataFrame(RP.rows(D117 / "status.jsonl")).drop_duplicates("seed", keep="last").set_index("seed")
    e120, l120, e117, dg = eval_frames()
    out = dict(faith=[], structure_pairs=[], control=[], summary={})
    L_ = ["# 120 report (generated by report120.py)", "",
          "Errors-zeroed (EZ) circuits = fitted with every masked site's SAE error zeroed (116 train patch). Scored "
          "with errors zeroed (EZ/zero, primary) and live (EZ/live). 117 = the errors-live circuits, scored live.", ""]
    # ------------------------------------------------------------------ faithfulness, paired
    L_ += ["## Faithfulness, paired by target (text = held-out strongest corpus text, Z/A/C/nec + pass; task = mean Z "
           "over held-out strongest task folds (folds passing))", "",
           "| pathway | target | circuit | n EZ / 117 | text EZ/zero | text EZ/live | text 117/live | task EZ/zero | "
           "task EZ/live | task 117/live |", "|---|---|---|---|---|---|---|---|---|---|"]
    for seed in keys:
        for cname in ("corpus", "task"):
            n1 = st120.loc[seed].get("n_%s" % cname) if seed in st120.index else None
            n0 = st117.loc[seed].get("n_%s" % cname) if seed in st117.index else None
            subs = [pick(df, seed, cname, "text") for df in (e120, l120, e117)]
            tsk = [pick(df, seed, cname, "task") for df in (e120, l120, e117)]
            if all(s is None or s.empty for s in subs + tsk):
                continue
            nf = lambda v: "-" if v is None or (isinstance(v, float) and np.isnan(v)) else "%d" % v  # noqa: E731
            L_.append("| %s | %s | %s | %s / %s | %s | %s | %s | %s | %s | %s |" % (
                pw_of[seed], seed, cname, nf(n1), nf(n0), *[cellfmt(s) for s in subs], *[task_cell(s) for s in tsk]))
            out["faith"].append(dict(seed=seed, circuit=cname, n120=None if n1 is None else float(n1),
                                     n117=None if n0 is None else float(n0),
                                     text=[None if s is None or s.empty else bool(s["pass"].any()) for s in subs],
                                     task_pass=[None if s is None or s.empty else int(s["pass"].sum()) for s in tsk],
                                     task_z=[None if s is None or s.empty else float(s.free0_tk.mean()) for s in tsk]))
    L_.append("")
    summ = []
    for cname in ("corpus", "task"):
        for lab, df in (("EZ/zero", e120), ("EZ/live", l120), ("117/live", e117)):
            g = df[(df.circuit == cname)]
            ts = g[(g.data == "text") & (g.held == "strong")]
            tk = g[(g.data == "task") & (g.held == "strong")]
            zt = tk.groupby("seed").free0_tk.mean()
            row = dict(circuit=cname, regime=lab, text_pass=int(ts["pass"].sum()), text_n=len(ts),
                       task_folds=int(tk["pass"].sum()), task_n=len(tk), task_z_in_band=int(((zt >= 0.75) & (zt <= 1.5)).sum()),
                       task_targets=len(zt), med_text_Z=float(ts.free0_tk.median()) if len(ts) else None)
            summ.append(row)
    for cname in ("corpus", "task"):
        ns = [f["n120"] for f in out["faith"] if f["circuit"] == cname and f["n120"] is not None]
        n0 = [f["n117"] for f in out["faith"] if f["circuit"] == cname and f["n117"] is not None]
        out["summary"]["median_n_%s" % cname] = [float(np.median(ns)) if ns else None, float(np.median(n0)) if n0 else None]
    L_ += ["| circuit | regime | text strong pass | task folds pass | targets with task Z in band | median text Z |",
           "|---|---|---|---|---|---|"]
    for r in summ:
        L_.append("| %s | %s | %d/%d | %d/%d | %d/%d | %s |" % (r["circuit"], r["regime"], r["text_pass"], r["text_n"],
                                                             r["task_folds"], r["task_n"], r["task_z_in_band"],
                                                             r["task_targets"], RP.fmt(r["med_text_Z"])))
    L_ += ["", "median members (EZ / 117): corpus %s, task %s" % (out["summary"]["median_n_corpus"],
                                                                 out["summary"]["median_n_task"]), ""]
    out["summary"]["faith"] = summ
    # ------------------------------------------------------------------ structure, paired
    s117 = {(r["seed"], r["circuit"], r["check"]): r for r in rep117["structure"]}
    s120 = {(r["seed"], r["circuit"], r["check"]): r for r in rep120["structure"]}
    L_ += ["## Structure checks, paired (shares as in 117; EZ frames have every upstream error zeroed)", "",
           "| pathway | target | circuit | check | EZ circuit | EZ null mean (p95) | error-free full | base | EZ rec | "
           "117 circuit | live full (117) | 117 rec |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    cnt = defaultdict(lambda: [0, 0, 0, 0])     # check-group -> [rec120, n120, rec117, n117]
    below = [0, 0]
    for k in sorted(set(s117) | set(s120), key=lambda x: (keys.index(x[0]), x[1], x[2])):
        a, b = s120.get(k), s117.get(k)
        grp = "head" if k[2] in L.CLASSES else "position/stage"
        for gname in (grp, "%s|%s" % (grp, k[1]), k[2]):
            if a:
                cnt[gname][0] += int(a["recovered"]); cnt[gname][1] += 1
            if b:
                cnt[gname][2] += int(b["recovered"]); cnt[gname][3] += 1
        if a and grp == "head" and a["full"] is not None:
            below[0] += int(a["share"] < a["full"]); below[1] += 1
        f = lambda r, key, p=3: RP.fmt(r[key], p) if r else "-"  # noqa: E731
        L_.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            pw_of[k[0]], k[0], k[1], k[2], f(a, "share"),
            ("%s (%s)" % (f(a, "null_mean"), f(a, "null_p95"))) if a else "-", f(a, "full"), f(a or b, "base"),
            ("yes" if a["recovered"] else "no") if a else "-", f(b, "share"), f(b, "full"),
            ("yes" if b["recovered"] else "no") if b else "-"))
        out["structure_pairs"].append(dict(key=list(k), ez=a, live=b))
    L_ += ["", "| check group | EZ recovered | 117 recovered |", "|---|---|---|"]
    for g in sorted(cnt):
        v = cnt[g]
        L_.append("| %s | %d/%d | %d/%d |" % (g, v[0], v[1], v[2], v[3]))
    L_ += ["", "EZ head-class checks with circuit share below the error-free full model's: %d/%d" % tuple(below), ""]
    out["summary"]["checks"] = {g: v for g, v in cnt.items()}
    out["summary"]["below_full_head"] = below
    # ------------------------------------------------------------------ positive control
    th = {}
    for lab, rep in (("ez", rep120), ("live", rep117)):
        for r in rep.get("top_heads", []):
            th[(lab, r["seed"], r["circuit"], r["frame"])] = r["top"]
    L_ += ["## Positive control: top head of the full model (error-free vs live) and of each circuit", "",
           "published = a published head of the target's task (any class); @role = also at that class's position", "",
           "| target | error-free full: top head | published | @role | live full (117): top head | published | @role | "
           "EZ corpus top | EZ task top |", "|---|---|---|---|---|---|---|---|---|"]
    ctl = defaultdict(lambda: [0, 0, 0])
    for seed in keys:
        pub = published(L.PATHWAYS[pw_of[seed]]["task"])
        cells = []
        for lab in ("ez", "live"):
            t = th.get((lab, seed, "-", "full"))
            if not t:
                cells += ["-", "-", "-"]
                continue
            l, h, r, v = t[0]
            isp = (l, h) in pub
            atr = isp and any(r == role for _, role in pub[(l, h)])
            cells += ["%d.%d@%s %.3f" % (l, h, r, v), "yes" if isp else "no", "yes" if atr else "no"]
            ctl[lab][0] += int(isp); ctl[lab][1] += int(atr); ctl[lab][2] += 1
            out["control"].append(dict(seed=seed, frame=lab, top=[l, h, r, v], published=isp, at_role=atr))
        circ = []
        for cname in ("corpus", "task"):
            t = th.get(("ez", seed, cname, "circuit"))
            if not t:
                circ.append("-")
                continue
            l, h, r, v = t[0]
            circ.append("%d.%d%s@%s %.3f" % (l, h, "*" if (l, h) in pub else "", r, v))
        L_.append("| %s | %s | %s | %s |" % (seed, " | ".join(cells), circ[0], circ[1]))
    L_ += ["", "full model ranks a published head first: error-free %d/%d (at its role %d), live %d/%d (at its role %d)"
           % (ctl["ez"][0], ctl["ez"][2], ctl["ez"][1], ctl["live"][0], ctl["live"][2], ctl["live"][1]), ""]
    out["summary"]["control"] = {k: v for k, v in ctl.items()}
    # Z pre ratio (circuit pre / full pre in the same frame)
    # ------------------------------------------------------------------ verdicts
    L_ += ["## Verdicts (pre-stated rule, as 117 applied it)", "", "| pathway / circuit | EZ | 117 |", "|---|---|---|"]
    for k in sorted(set(rep120["verdicts"]) | set(rep117["verdicts"])):
        a, b = rep120["verdicts"].get(k), rep117["verdicts"].get(k)
        fm = lambda v: "-" if not v else "%s (%d/%d maj; %s)" % (v["verdict"], v["majority"], v["n"],  # noqa: E731
                                                                 ", ".join(v["half"]) or "none")
        L_.append("| %s | %s | %s |" % (k, fm(a), fm(b)))
    L_.append("")
    out["verdicts"] = dict(ez=rep120["verdicts"], live=rep117["verdicts"])
    # ------------------------------------------------------------------ diagnostic
    if not dg.empty:
        L_ += ["## Diagnostic: 117's original (errors-live-fitted) circuits re-scored with errors zeroed (no refit)", "",
               "| circuit | text strong pass: live (this run) | zeroed | task folds pass: live (117 rows) | zeroed | "
               "text live row = 117 row (max abs diff Z/A/C/nec) |", "|---|---|---|---|---|---|"]
        for cname in ("corpus", "task"):
            g = dg[dg.circuit == cname]
            tz = g[(g.data == "text") & (g.err_mode == "zero")]
            tl = g[(g.data == "text") & (g.err_mode == "live")]
            kz = g[(g.data == "task") & (g.err_mode == "zero")]
            ref = e117[(e117.circuit == cname) & (e117.held == "strong")]
            kl = ref[(ref.data == "task") & ref.set_index(["seed", "fold"]).index.isin(
                kz.set_index(["seed", "fold"]).index)]
            m = tl.merge(ref[ref.data == "text"], on=["seed", "circuit", "data", "held", "fold"], suffixes=("", "_117"))
            md = max((float((m[c] - m[c + "_117"]).abs().max()) for c in COLS), default=float("nan")) if len(m) else float("nan")
            L_.append("| %s | %d/%d | %d/%d | %d/%d | %d/%d | %s |" % (
                cname, int(tl["pass"].sum()), len(tl), int(tz["pass"].sum()), len(tz), int(kl["pass"].sum()), len(kl),
                int(kz["pass"].sum()), len(kz), RP.fmt(md, 4)))
            out["summary"]["diag_%s" % cname] = dict(text_live=[int(tl["pass"].sum()), len(tl)],
                                                     text_zero=[int(tz["pass"].sum()), len(tz)],
                                                     task_live=[int(kl["pass"].sum()), len(kl)],
                                                     task_zero=[int(kz["pass"].sum()), len(kz)], max_diff=md,
                                                     med_text_Z_live=float(tl.free0_tk.median()) if len(tl) else None,
                                                     med_text_Z_zero=float(tz.free0_tk.median()) if len(tz) else None)
        L_.append("")
    # Z-frame pre ratio and train-patch calls
    if "train_err_calls" in e120:
        L_.append("train error-ablation calls (max over rows): %d" % int(pd.to_numeric(e120.train_err_calls).max()))
    (C.OUT / "report120.md").write_text("\n".join(L_) + "\n", encoding="utf-8")
    (C.OUT / "report120.json").write_text(json.dumps(out, indent=1, default=float), encoding="utf-8")
    print("\n".join(L_))


if __name__ == "__main__":
    main()
