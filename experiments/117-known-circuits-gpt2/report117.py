import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import lib117 as L  # noqa: E402
import merge as MG  # noqa: E402  (062's pass rule and vacuous set: single source)

D = L.OUT / "wcm" / "dan215"
EXPECT = {
    "IOI-NM": ["s_inhibition", "induction", "duplicate_token", "previous_token", "name_mover", "ioi_io_pos"],
    "IOI-SI": ["induction", "duplicate_token", "previous_token", "ioi_s2_pos"],
    "IOI-IND": ["duplicate_token", "previous_token", "induction"],
    "GT-MLP": ["gt_heads", "gt_yy_pos", "gt_late_mlp_end"],
}


def rows(p):
    out = []
    if p.exists():
        for line in open(p):
            try:
                out.append(json.loads(line))
            except ValueError:
                pass
    return out


def in_scope_heads(heads, layer, kind):
    """Heads strictly upstream of the target: attn target at L -> layers < L; mlp target at L -> layers <= L."""
    return [(l, h) for (l, h) in heads if (l < layer or (kind == "mlp" and l == layer))]


def share(mass, total, check, layer, kind):
    """Share of one check; None when nothing of it is in scope.
    Head classes: class-head mass at the class position / ALL attention-site mass in scope (every head, every
    position). Attention-out SAE latents decompose each layer's attention output exactly over heads, so this is a
    proper decomposition; residual-site latents re-decompose the same stream and are left out of the denominator
    (amendment, README).
    Position checks: mass at the role / total mass (every site); the late-MLP check: MLP mass at END in L8+ (below the
    target) / all MLP mass."""
    if check in L.CLASSES:
        c = L.CLASSES[check]
        hs = set(in_scope_heads(c["heads"], layer, kind))
        if not hs:
            return None
        att = sum(m for (l, k, h, r), m in mass.items() if k == "attn" and h >= 0)
        v = sum(m for (l, k, h, r), m in mass.items() if k == "attn" and (l, h) in hs and r == c["role"])
        return v / att if att > 0 else float("nan")
    c = L.POSITION_CHECKS[check]
    lays = c.get("layers")
    if lays is not None:
        lays = [x for x in lays if x < layer]
        if not lays:
            return None
    v, den = 0.0, 0.0
    for (l, k, h, r), m in mass.items():
        if c.get("kind") and k != c["kind"]:
            continue
        den += m
        if r != c["role"]:
            continue
        if lays is not None and l not in lays:
            continue
        v += m
    if not c.get("kind"):
        den = total
    return v / den if den > 0 else float("nan")


def base_rate(check, layer, kind):
    """Uniform base rate of a head class: class heads in scope / all heads in the attention layers in scope (081's
    T4 base); None for position checks."""
    if check not in L.CLASSES:
        return None
    hs = in_scope_heads(L.CLASSES[check]["heads"], layer, kind)
    n_layers = layer + (1 if kind == "mlp" else 0)
    return len(hs) / (L.N_HEADS * n_layers) if hs else None


def mass_of(r):
    return {(int(a), str(b), int(c), str(d)): float(v) for a, b, c, d, v in r["mass"]}


def fmt(x, p=2):
    return "-" if x is None or (isinstance(x, float) and np.isnan(x)) else ("%.*f" % (p, x))


def main():
    sel = json.loads((L.OUT / "targets.json").read_text())
    ev = pd.DataFrame([r for r in rows(D / "eval.jsonl") if "error" not in r])
    st = pd.DataFrame(rows(D / "status.jsonl"))
    if not st.empty:
        st = st.drop_duplicates("seed", keep="last").set_index("seed")
    lines = ["# 117 report (generated by report117.py)", ""]
    rep = dict(faith=[], structure=[], verdicts={})
    # ---------------------------------------------------------------- faithfulness
    if not ev.empty:
        ev = ev.drop_duplicates(["seed", "circuit", "data", "held", "fold"], keep="last").reset_index(drop=True)
        for c in MG.HEAD + ["phi_sup_blind_tk", "a_pos_tk"] + MG.VAC_BASE:
            if c in ev:
                ev[c] = pd.to_numeric(ev[c], errors="coerce")
        ev["vac"] = MG.vacuous(ev).values
        ev["pass"] = False
        ok = ~ev.vac
        ev.loc[ok, "pass"] = MG.passes(ev[ok]).values
        lines += ["## Faithfulness (production scorer; Z / A / C = free0_tk / freeM_topk_tk / freeN_topk_tk, nec = "
                  "phi_sup_blind_tk; pass = Z, A, C in [0.75, 1.5] and nec >= 0.9; task = mean over held-out folds)",
                  "",
                  "| pathway | target | circuit | n | text strong Z/A/C/nec pass | text mid pass | task strong Z/A/C/nec "
                  "(folds) pass k/n | task mid pass |", "|---|---|---|---|---|---|---|---|"]
        for (seed, cname), g in ev.groupby(["seed", "circuit"], sort=False):
            def cell(sub):
                if sub.empty:
                    return "-", None
                m = sub[MG.HEAD + ["phi_sup_blind_tk"]].mean()
                return "%.2f/%.2f/%.2f/%.2f" % tuple(m.values), sub
            ts = g[(g.data == "text") & (g.held == "strong")]
            tm = g[(g.data == "text") & (g.held == "mid")]
            ks = g[(g.data == "task") & (g.held == "strong")]
            km = g[(g.data == "task") & (g.held == "mid")]
            c_ts, _ = cell(ts)
            c_ks, _ = cell(ks)
            n = st.loc[seed, "n_%s" % cname] if seed in st.index and ("n_%s" % cname) in st else None
            pw = g.pathway.iloc[0]
            lines.append("| %s | %s | %s | %s | %s %s | %s | %s %d/%d | %s |" % (
                pw, seed, cname, fmt(n, 0) if n is not None else "-", c_ts,
                ("vac" if bool(ts.vac.any()) else ("pass" if bool(ts["pass"].any()) else "fail")) if len(ts) else "",
                ("vac" if bool(tm.vac.any()) else ("pass" if bool(tm["pass"].any()) else "fail")) if len(tm) else "-",
                c_ks, int(ks["pass"].sum()), len(ks),
                ("vac" if bool(km.vac.any()) else ("pass" if bool(km["pass"].any()) else "fail")) if len(km) else "-"))
            rep["faith"].append(dict(seed=seed, circuit=cname, pathway=pw, n=None if n is None else float(n),
                                     text_strong=ts[MG.HEAD + ["phi_sup_blind_tk", "pass", "vac"]].to_dict("records"),
                                     text_mid=tm[MG.HEAD + ["phi_sup_blind_tk", "pass", "vac"]].to_dict("records"),
                                     task_strong=ks[MG.HEAD + ["phi_sup_blind_tk", "pass", "vac"]].to_dict("records"),
                                     task_mid=km[MG.HEAD + ["phi_sup_blind_tk", "pass", "vac"]].to_dict("records")))
        lines.append("")
    # ---------------------------------------------------------------- structure
    sr = rows(D / "structure.jsonl")
    by = defaultdict(list)
    for r in sr:
        by[(r["seed"], r["circuit"], r["frame"])].append(r)
    keys = [c["key"] for p in sel["pathways"].values() for c in p["chosen"]]
    lines += ["## Structure checks (share of total |attribution| mass of the target's pre-activation; held-out task "
              "prompts)", "",
              "head classes: share of attention-site mass; positions: share of all mass; late MLP: share of MLP mass. "
              "recovered = circuit share >= 2x null mean AND > null 95th percentile (20 random matched draws) AND (head "
              "classes) >= 2x the uniform head base rate", "",
              "| pathway | target | circuit | Z pre (frame/full) | check | circuit | null mean (p95) | x null | full "
              "model | base | recovered |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    rec_tab = defaultdict(dict)       # (pathway, circuit) -> seed -> {check: bool}
    for seed in keys:
        layer, kind, _ = L.parse(seed)
        pname = next(p for p, d in sel["pathways"].items() if any(c["key"] == seed for c in d["chosen"]))
        full = by.get((seed, "-", "full"), [])
        fm = mass_of(full[0]) if full else None
        f_tot = sum(fm.values()) if fm else None
        f_pre = full[0]["pre"] if full else None
        for cname in ("corpus", "task"):
            cr = by.get((seed, cname, "circuit"), [])
            nr = by.get((seed, cname, "null"), [])
            if not cr:
                continue
            cm = mass_of(cr[0]); c_tot = sum(cm.values())
            nm = [mass_of(x) for x in nr]
            zr = cr[0]["pre"] / f_pre if f_pre else float("nan")
            for chk in EXPECT[pname]:
                s = share(cm, c_tot, chk, layer, kind)
                if s is None:
                    continue
                ns = np.array([share(m, sum(m.values()), chk, layer, kind) for m in nm], dtype=float)
                ns = ns[~np.isnan(ns)]
                fs = share(fm, f_tot, chk, layer, kind) if fm else None
                mu = float(ns.mean()) if len(ns) else float("nan")
                p95 = float(np.percentile(ns, 95)) if len(ns) else float("nan")
                br = base_rate(chk, layer, kind)
                recov = bool(len(ns) and s >= 2 * mu and s > p95 and (br is None or s >= 2 * br))
                rec_tab[(pname, cname)].setdefault(seed, {})[chk] = recov
                lines.append("| %s | %s | %s | %s | %s | %.3f | %.3f (%.3f) | %s | %s | %s | %s |" % (
                    pname, seed, cname, fmt(zr), chk, s, mu, p95, fmt(s / mu if mu > 0 else float("nan"), 1),
                    fmt(fs, 3), fmt(br, 3), "yes" if recov else "no"))
                rep["structure"].append(dict(pathway=pname, seed=seed, circuit=cname, check=chk, share=s,
                                             null_mean=mu, null_p95=p95, n_draws=int(len(ns)), full=fs, base=br,
                                             recovered=recov, z_pre_ratio=zr, n=cr[0]["n"]))
    # ---------------------------------------------------------------- descriptive: top heads
    pub = {}
    for cn, c in L.CLASSES.items():
        for lh in c["heads"]:
            pub.setdefault(lh, []).append(cn)
    lines += ["", "## Top upstream heads by attention-site mass (descriptive; * = a published head of any class)", "",
              "| target | frame | top 6 head@position (share of attention mass) |", "|---|---|---|"]
    for seed in keys:
        for cname, frame in (("-", "full"), ("corpus", "circuit"), ("task", "circuit")):
            rr = by.get((seed, cname, frame), [])
            if not rr:
                continue
            m = mass_of(rr[0])
            att = sum(v for (l, k, h, r), v in m.items() if k == "attn" and h >= 0)
            hm = defaultdict(float)
            for (l, k, h, r), v in m.items():
                if k == "attn" and h >= 0:
                    hm[(l, h, r)] += v
            top = sorted(hm.items(), key=lambda kv: -kv[1])[:6]
            if not att:  # 120: a collapsed circuit can have zero attention mass (never happens in 117's rows)
                att, top = 1.0, []
            cell = ", ".join("%d.%d%s@%s %.2f" % (l, h, "*" if (l, h) in pub else "", r, v / att) for (l, h, r), v in top)
            lines.append("| %s | %s | %s |" % (seed, "full model" if frame == "full" else cname, cell))
            rep.setdefault("top_heads", []).append(dict(seed=seed, frame=frame, circuit=cname,
                                                        top=[[l, h, r, v / att] for (l, h, r), v in top]))
    lines += ["", "## Verdicts (pre-stated rule)", "",
              "| pathway | circuit | targets with a majority of checks recovered | checks recovered in >= half of "
              "targets | verdict |", "|---|---|---|---|---|"]
    # secondary (not pre-stated, reported beside it): only circuits that are faithful on the held-out task prompts
    # (mean task-strong Z in [0.75, 1.5]); a collapsed fit has no structure to test
    zt = {}
    if not ev.empty:
        for (seed, cname), g in ev[(ev.data == "task") & (ev.held == "strong")].groupby(["seed", "circuit"]):
            zt[(seed, cname)] = float(g["free0_tk"].mean())
    rows_v = [(k, v, False) for k, v in sorted(rec_tab.items())]
    for (pname, cname), tab in sorted(rec_tab.items()):
        sub = {s: d for s, d in tab.items() if 0.75 <= zt.get((s, cname), float("nan")) <= 1.5}
        rows_v.append(((pname, cname + " [task-faithful only]"), sub, True))
    for (pname, cname), tab, _sec in rows_v:
        n_t = len(tab)
        if n_t == 0:
            lines.append("| %s | %s | 0/0 | - | (no circuit) |" % (pname, cname))
            continue
        maj = sum(1 for d in tab.values() if sum(d.values()) > len(d) / 2)
        checks = sorted({c for d in tab.values() for c in d})
        half = [c for c in checks if sum(d.get(c, False) for d in tab.values()) >= sum(c in d for d in tab.values()) / 2
                and any(d.get(c, False) for d in tab.values())]
        verdict = "RECOVERED" if maj > n_t / 2 else ("PARTIAL" if half else "NOT RECOVERED")
        lines.append("| %s | %s | %d/%d | %s | %s |" % (pname, cname, maj, n_t, ", ".join(half) or "none", verdict))
        rep["verdicts"]["%s|%s" % (pname, cname)] = dict(majority=maj, n=n_t, half=half, verdict=verdict)
    (L.OUT / "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (L.OUT / "report.json").write_text(json.dumps(rep, indent=1, default=float), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
