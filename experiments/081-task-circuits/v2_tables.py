"""Experiment 081, v2 local run (2026-10-27): the tables of README "v2 local run" (CPU, reads out_v2/ only).

  out_v2/tables.md   competence | calibration A/B (logit_norm gap vs gap_term, v2) and the v1 control | per task x arm x
                     lambda on the held-out split (task metric and fitted objective: Z / A_sp / C_sp, necessity, pass,
                     Z at alpha = 1, size, timings) | U / W size ratios | random null | structure checks (report.json)
  PYTHONPATH=src python -X utf8 experiments/081-task-circuits/v2_tables.py
"""
import json
import statistics as st
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import task_common as C  # noqa: E402

O = HERE / "out_v2"
OM = O / C.MODEL


def rows(p):
    p = Path(p)
    if not p.exists():
        return []
    out = {}
    for line in open(p):
        try:
            r = json.loads(line)
        except Exception:  # noqa: BLE001
            continue
        out[(r["task"], r["arm"], r["lam"], int(r.get("draw", -1)), str(r.get("lr")))] = r
    return list(out.values())


def f(v, d=2):
    return ("%%.%df" % d) % v if isinstance(v, (int, float)) and not isinstance(v, bool) and v == v else "-"


def frames(r, pre):
    return " / ".join(f(r.get("%s_%s" % (pre, k))) for k in ("free0", "freeM_topk", "freeN_topk")) + \
        "; nec %s; %s" % (f(r.get(pre + "_nec")), "**pass**" if C.passes(r, pre) else "fail")


def main():
    L = ["# 081 v2 local run: tables (generated by v2_tables.py)", ""]
    comp = json.loads((O / "probe" / "competence.json").read_text())["tasks"]
    L += ["## Competence (held-out, full model)", "",
          "| task | n | mean metric | share correct | cf gap | verdict |", "|---|---|---|---|---|---|"]
    for k, v in comp.items():
        h = v["held"]
        L.append("| %s | %d | %s | %.0f%% | %s | %s |" % (k, h["n"], f(h["mean_clean"], 3), 100 * h["frac_correct"],
                                                         f(h.get("cf_gap")), "competent" if v["competent"] else "NOT"))
    L += ["", "## Calibration (training rows re-split 75 / 25; W, lr 0.05, 400 steps)", "",
          "Z / A_sp / C_sp | necessity | rule, on the task metric and on the fitted objective.", "",
          "| task | WCM | logit_norm | lambda | n | task: Z / A / C, nec, rule | objective: Z / A / C, nec, rule | "
          "term scales | t_fit s |", "|---|---|---|---|---|---|---|---|---|"]
    for tag, ver, norm in (("calib_gap", "v2", "gap"), ("calib_gap_term", "v2", "gap_term"),
                           ("calib_v1_gap", "v1", "gap")):
        for r in sorted(rows(O / tag / "eval.jsonl"), key=lambda r: (r["task"], r["lam_value"])):
            sc = r.get("logit_term_scales")
            L.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                r["task"], ver, norm, r["lam"], r.get("n"), frames(r, "task"), frames(r, "obj"),
                "/".join(f(sc[k], 1) for k in ("zero", "floor", "pos") if k in sc) if sc else "-",
                f(r.get("t_fit"), 0)))
    ev = [r for r in rows(OM / "eval.jsonl") if not r.get("error")]
    errs = [r for r in rows(OM / "eval.jsonl") if r.get("error")]
    L += ["", "## Held-out results per task (out_v2/%s)" % C.MODEL, "",
          "| task | arm | lambda | n | task: Z / A / C, nec, rule | objective: Z / A / C, nec, rule | Z(alpha=1) | "
          "acc(Z) | t_fit s | t_score s |", "|---|---|---|---|---|---|---|---|---|---|"]
    by = defaultdict(list)
    for r in ev:
        by[r["task"]].append(r)
    for t in sorted(by):
        for r in sorted([r for r in by[t] if r["arm"] != "RND"], key=lambda r: (r["arm"], r["lam_value"])):
            L.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                t, r["arm"], r["lam"], r.get("n"), frames(r, "task"), frames(r, "obj"), f(r.get("task_free0_a1")),
                f(r.get("task_acc_free0")), f(r.get("t_fit"), 0), f(r.get("t_score"), 0)))
    L += ["", "## Claim 2: U / W size (task metric)", "",
          "| task | W n at Z 0.8 | U n at Z 0.8 | ratio | smallest passing W | smallest passing U | U max n |",
          "|---|---|---|---|---|---|---|"]
    for t in sorted(by):
        cw = C.curve([r for r in by[t] if r["arm"] == "W"])
        cu = C.curve([r for r in by[t] if r["arm"] == "U"])
        sr = C.size_ratio(cw, cu)
        L.append("| %s | %s | %s | %s | %s | %s | %s |" % (t, f(sr["n_reach_W"], 0), f(sr["n_reach_U"], 0),
                                                          f(sr["reach_ratio"]), sr["pass_W"], sr["pass_U"],
                                                          sr["u_max_n"]))
    L += ["", "## Random null (fitted coefficients, support matched to W's per-site counts)", "",
          "| task | W lambda | n | draws | task Z median [min, max] | A median | C median | pass | W's Z / A / C |",
          "|---|---|---|---|---|---|---|---|---|"]
    for t in sorted(by):
        rn = defaultdict(list)
        for r in by[t]:
            if r["arm"] == "RND":
                rn[r["lam"]].append(r)
        for lt, rs in sorted(rn.items()):
            zs = [r["task_free0"] for r in rs if isinstance(r.get("task_free0"), float)]
            w = [r for r in by[t] if r["arm"] == "W" and r["lam"] == lt]
            L.append("| %s | %s | %s | %d | %s [%s, %s] | %s | %s | %d / %d | %s |" % (
                t, lt, rs[0].get("n"), len(rs), f(st.median(zs)) if zs else "-", f(min(zs)) if zs else "-",
                f(max(zs)) if zs else "-",
                f(st.median([r["task_freeM_topk"] for r in rs if isinstance(r.get("task_freeM_topk"), float)] or [None])),
                f(st.median([r["task_freeN_topk"] for r in rs if isinstance(r.get("task_freeN_topk"), float)] or [None])),
                sum(C.passes(r) for r in rs), len(rs),
                " / ".join(f(w[0].get("task_" + k)) for k in ("free0", "freeM_topk", "freeN_topk")) if w else "-"))
    rep = OM / "report.json"
    if rep.exists():
        R = json.loads(rep.read_text())
        st_, pri = R.get("structure") or {}, R.get("primary") or {}
        L += ["", "## Structure vs published circuits (primary W circuit; report.py section 4)", "",
              "value = enrichment (share of the attention members' head-attributed |attribution| in the class's layers, "
              "over the uniform base rate; found at >= 2x), or the stated statistic.", "",
              "| task | primary lambda (n, passes) | check | value | share | base | held |",
              "|---|---|---|---|---|---|---|"]
        for t, d in sorted(st_.items()):
            p = pri.get(t, {})
            for k, c in sorted(d.items()):
                L.append("| %s | %s (%s, %s) | %s | %s | %s | %s | %s |" % (
                    t, p.get("lam"), p.get("n"), p.get("passing"), k, f(c.get("value")), f(c.get("share")),
                    f(c.get("base")), c.get("held")))
    if errs:
        L += ["", "## Errors", ""] + ["- %s %s %s: %s" % (r["task"], r["arm"], r["lam"], r["error"]) for r in errs]
    (O / "tables.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
