def purpose(p):
    for f in sorted(glob.glob(os.path.join(p, "*.py"))):
        try:
            d = (ast.get_docstring(ast.parse(open(f, encoding="utf-8").read())) or "")
            d = d.strip().splitlines()
            if d:
                return d[0].replace("|", "/")[:110]
        except Exception:
            pass
    return ""


def main():
    paper = PAPER.read_text(encoding="utf-8")
    lines = ["# Campaign index", "",
             "One line per campaign, generated by `make_index.py` from each runner's "
             "docstring. `paper` = directory named in a `% data:` comment in main.tex.",
             "", "| campaign | paper | README | purpose |", "|---|---|---|---|"]
    kept = 0
    for d in sorted(os.listdir(ROOT)):
        p = ROOT / d
        if not p.is_dir() or d in ("_archive", "__pycache__"):
            continue
        readme = "Y" if any(x.lower().startswith("readme") for x in os.listdir(p)) else "-"
        lines.append("| `%s` | %s | %s | %s |" % (d, "Y" if d in paper else "-", readme, purpose(p)))
        kept += 1
    lines += ["", "## Merged into another campaign", "", "| former campaign | now in |", "|---|---|"]
    for a, b in sorted(MERGED.items()):
        lines.append("| `%s` | `%s` |" % (a, b))
    lines += ["", "## Kept as data sources (own framing retired)", "", "| campaign | consumed by |", "|---|---|"]
    for a, b in sorted(DATA_SOURCES.items()):
        lines.append("| `%s` | %s |" % (a, b))
    lines += ["", "## Archived (`_archive/`, gitignored; kept locally, not evidence)", "",
              "| campaign | why |", "|---|---|"]
    arch = ROOT / "_archive"
    n_arch = 0
    if arch.is_dir():
        for d in sorted(os.listdir(arch)):
            lines.append("| `%s` | %s |" % (d, ARCHIVED.get(d, "(no reason recorded)")))
            n_arch += 1
    (ROOT / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="")
    print("INDEX.md: %d kept, %d archived" % (kept, n_arch))


if __name__ == "__main__":
    main()
